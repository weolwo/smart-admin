package solvela.member.code;

/**
 * 校验验证码的结果。<b>通道无关</b>。
 *
 * <p>{@link #NOT_FOUND} 合并了「从没发过」和「已过期」—— Redis 里两者都是「键不存在」，
 * 分不出来；硬要分就得再存一份已过期的记录，而那除了给攻击者一个
 * 「这个目标刚才发过码」的信号之外没有任何用处。
 */
public enum CodeVerifyOutcome {

    /** 通过。<b>验证码已被消费</b>，同一个码不能再用第二次。 */
    OK,

    /** 没有待校验的验证码：从没发过，或者已经过期。 */
    NOT_FOUND,

    /** 验证码不对。剩余次数由存储层计数，用尽后转为 {@link #TOO_MANY_ATTEMPTS}。 */
    MISMATCH,

    /**
     * 连续输错次数用尽，验证码<b>已被作废</b>，必须重新发送。
     *
     * <p>🔴 这一档不是体验优化，是必需的：6 位数字只有 100 万种组合，
     * 而验证码有 5 分钟有效期 —— 没有次数上限的话，一个脚本几秒钟就能穷举完。
     */
    TOO_MANY_ATTEMPTS,
}
