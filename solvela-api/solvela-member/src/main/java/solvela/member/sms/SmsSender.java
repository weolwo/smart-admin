package solvela.member.sms;

import solvela.member.api.SmsScene;

/**
 * 把一条短信发出去。<b>目前全仓没有任何实现</b>。
 *
 * <h3>为什么先定接口，实现留空</h3>
 * 接短信服务商卡的<b>不是钱，是资质与报备</b>：企业实名、签名报备、模板报备，
 * 通常要一两个工作日。而验证码这条链路的其余部分（限频、失败次数上限、
 * 消费语义、注册校验）与厂商无关，没必要一起等。
 *
 * <p>所以：接口在这里，dev / test 走 {@code sms-transport: LOG} 把码打进日志
 * 就能把整条链路跑通、把用例写完；等厂商接好，加一个实现类、把生产配成 REAL 即可，
 * <b>这条链路上的其它代码一行都不用动</b>。
 *
 * <h3>🔴 实现时要注意的两件事</h3>
 * <ul>
 *   <li><b>发送失败要抛异常，不要吞</b>。调用方靠异常把刚存的码删掉 ——
 *       不删的话，用户在收不到短信的同时还会被 60 秒冷却挡住；</li>
 *   <li><b>不要在实现里重试</b>。短信按条计费，一次失败重试三次就是三倍账单，
 *       而多数失败（号码格式、被运营商拦截、余额不足）重试也不会成功。
 *       真要重试，那是调用方基于失败原因的决定，不是发送器的。</li>
 * </ul>
 *
 * @Date 2026-09-10
 */
public interface SmsSender {

    /**
     * 发一条验证码短信。
     *
     * @param phone   已规范化的 11 位手机号
     * @param scene   用途。实现按它选模板 —— 国内厂商的模板是<b>要报备的</b>，
     *                一个场景一个模板号，不能拿注册的模板去发重置密码
     * @param code    验证码
     * @param minutes 有效期（分钟），多数模板文案里要带
     * @throws RuntimeException 发送失败。<b>必须抛</b>，见类注释
     */
    void send(String phone, SmsScene scene, String code, long minutes);

    /**
     * 这个发送器<b>真的能把短信发出去</b>吗。
     *
     * <p>只有 {@link UnavailableSmsSender} 会返回 false。存在的理由是让
     * 「配了 REAL 但根本没接厂商」在<b>启动时</b>就炸，而不是等第一个真实用户
     * 点下「获取验证码」—— 那时它表现为一个 500，而没人在看日志。
     *
     * <p>真实实现<b>不要覆写</b>：它不是「厂商此刻通不通」的健康检查
     * （那需要真调一次接口，每次启动花掉一条短信的钱），只是「有没有实现」。
     */
    default boolean available() {
        return true;
    }
}
