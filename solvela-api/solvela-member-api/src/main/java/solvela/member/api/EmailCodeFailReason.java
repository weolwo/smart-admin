package solvela.member.api;

/**
 * 发送邮箱验证码失败的原因。域只说原因，<b>措辞由调用方定</b>。
 *
 * <p>🔴 这里<b>没有</b>「邮箱不存在」「邮箱已被注册」这两个值，而那不是遗漏：
 * 它们会把发码接口变成一个<b>账号枚举器</b> —— 输入一个邮箱，看回的是
 * 「已注册」还是「未注册」，就知道这个人是不是本站用户。
 *
 * <p>正确做法是这两种情况都<b>静默成功</b>（返回 ok 但不真的发信），
 * 与 {@code LoginService.requireSendableEmployee} 对「账号不存在」的处理同一个思路。
 * 用户体验上的代价是「填错邮箱时不会被提醒」，而那远好过送出一个枚举接口。
 */
public enum EmailCodeFailReason {

    /**
     * 邮箱格式不对。<b>可以明说</b>：一个非法的串本来就不可能是任何人的邮箱，不泄露任何信息。
     * 判据同 {@link AuthFailReason#BAD_PHONE_FORMAT}。
     */
    BAD_EMAIL_FORMAT,

    /** 上一封发出去还不到冷却时间。剩余秒数见 {@link EmailCodeSendResult#retryAfterSeconds()}。 */
    TOO_FREQUENT,

    /**
     * 这个邮箱（或这个 IP）今天发得太多了。
     *
     * <p>挡的不只是骚扰：验证码接口是个<b>免费的邮件发射器</b>，
     * 不限量就会被拿去给别人发垃圾，而发件人显示的是我们的域名 ——
     * 后果是整个域名进黑名单，此后所有系统邮件都进垃圾箱。
     */
    DAILY_LIMIT_REACHED,

    /**
     * 邮件发不出去（SMTP 挂了、账号密码不对、被限流）。
     *
     * <p>与上面几个不同，这是<b>我们自己的问题</b>，要如实告诉用户「稍后再试」
     * 而不是让他以为自己填错了。同时必须打错误日志 —— 它不该被当成正常业务失败吞掉。
     */
    SEND_FAILED,
}
