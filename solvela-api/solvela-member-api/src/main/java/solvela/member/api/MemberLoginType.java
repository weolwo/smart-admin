package solvela.member.api;

/**
 * 登录方式：<b>用什么找人</b> + <b>用什么证明</b>。
 *
 * <h3>为什么是一个扁平枚举，而不是「身份类型 × 凭据类型」两个</h3>
 * 两个正交枚举会让矩阵里<b>空着的那一格在类型上合法</b> ——
 * 手机号 + 验证码这一格做不到（全仓没有短信基础设施），
 * 而两个枚举的组合能表达它，于是只能在运行期报错。
 *
 * <p>扁平枚举配 {@code switch} 表达式：新增一种登录方式时<b>编译不过</b>，
 * 而不是悄悄落进某个兜底分支。这也是本仓一贯的做法（见 {@code AuthFailReason} 的用法）。
 *
 * <h3>🔴 类型由调用方【显式传入】，不从输入格式猜</h3>
 * 「看着像手机号就当手机号」这种推断错一次的表现是：用邮箱登录时按手机号去查，
 * 查无此人 —— 而用户看到的是「手机号或密码错误」，指向一个他根本没输入过的东西。
 *
 * @Date 2026-09-09
 */
public enum MemberLoginType {

    /** 手机号 + 密码。系统最早的、也是<b>唯一没有被验证过</b>的通道（还没有短信验证码）。 */
    PHONE_PASSWORD,

    /**
     * 邮箱 + 密码。
     *
     * <p>只有<b>设过密码</b>的会员能用 —— 邮箱验证码注册出来的会员密码可以为空
     * （{@code t_member.password} 允许 NULL，DDL 注释写着「验证码登录可为空」），
     * 那种会员走 {@link #EMAIL_CODE}。
     */
    EMAIL_PASSWORD,

    /**
     * 邮箱 + 验证码，免密登录。
     *
     * <p>给「设过邮箱但忘了密码、又不想走重置流程」的用户，
     * 以及邮箱注册时没设密码的会员。
     */
    EMAIL_CODE,
}
