package solvela.member.api;

/**
 * 这次发码<b>要不要真的把信寄出去</b>。
 *
 * <h3>🔴 SUPPRESS 存在的唯一理由：堵住一个账号枚举漏洞</h3>
 * 登录与重置密码这两个场景，邮箱没有对应会员时必须<b>静默成功</b> ——
 * 如实回答「这个邮箱没注册」等于送出一个账号枚举接口。
 *
 * <p>但只在发送这一步静默是<b>不够的</b>，漏洞会转移到校验那一步：
 * <pre>
 *   有账号 → 存了码 → 随便输个错码 → 「验证码错误」
 *   没账号 → 没存码 → 随便输个错码 → 「验证码已失效」
 * </pre>
 * 两个回答不同，攻击者照样能把用户枚举出来。发送那一步藏住的东西，
 * 在校验那一步又漏了出去。
 *
 * <p>所以 SUPPRESS 的语义是<b>「照常存码、照常计入限频，只是不寄信」</b>：
 * 两条路径此后的行为逐字相同。代价是一个会自然过期的 Redis 键。
 *
 * @Date 2026-09-09
 */
public enum MailDelivery {

    /** 正常寄信。 */
    DELIVER,

    /**
     * 存码但不寄信。
     *
     * <p>⚠️ <b>不要拿它当「调试时别真发信」的开关。</b>那种需求应当在
     * {@code spring.mail} 配置或 MailService 一层解决 ——
     * 混进来之后，这个枚举就同时表达两件事，而其中一件是安全约束。
     */
    SUPPRESS,
}
